// Writes src/render/font-metrics.generated.ts: advance widths (per 1 em) of IBM Plex Sans 400/600 for the
// characters the subset contains. The renderer measures text with it, without a DOM.
import { readFile, writeFile } from 'node:fs/promises';
import * as fontkitNs from '../../lib/vendor/fontkit/fontkit.esm.min.js';

const fontkit = fontkitNs.default ?? fontkitNs;
const out = { family: '', unitsPerEm: 1000, weights: {} };
for (const w of [400, 600]) {
  const buf = await readFile(new URL(`../public/fonts/plex-sans-${w}.ttf`, import.meta.url));
  const font = fontkit.create(buf);
  out.family = font.familyName;
  const widths = {};
  for (const cp of font.characterSet) {
    if (cp < 32 || cp > 0x2fff) continue;
    widths[String.fromCodePoint(cp)] = Math.round((font.glyphForCodePoint(cp).advanceWidth / font.unitsPerEm) * 1000);
  }
  out.weights[w] = widths;
}
const text = `// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/gen-font-metrics.mjs. Do not edit.\nexport const FONT_METRICS: { family: string; weights: Record<number, Record<string, number>> } = ${JSON.stringify({ family: out.family, weights: out.weights })};\n`;
await writeFile(new URL('../src/render/font-metrics.generated.ts', import.meta.url), text);
console.log(
  out.family,
  Object.keys(out.weights[400]).length,
  'glyphs; has Δ ³ ² ₂ Ü:',
  ['Δ', '³', '²', '₂', 'Ü', '≠'].map((c) => c in out.weights[400]).join(' '),
);
