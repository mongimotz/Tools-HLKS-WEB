// Writes src/symbols/index.generated.ts with a static import of every symbol JSON (works in Vite and in Node/tsx).
// Usage: node scripts/gen-symbol-index.mjs [--check]   (--check fails when the index is out of date)
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../src/symbols/', import.meta.url));
const OUT = join(DIR, 'index.generated.ts');

async function files(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await files(p)));
    else if (e.name.endsWith('.json')) out.push(p);
  }
  return out.sort();
}

const list = await files(DIR);
const ids = new Set();
for (const f of list) {
  const def = JSON.parse(await readFile(f, 'utf8'));
  if (ids.has(def.id)) throw new Error(`duplicate symbol id ${def.id} in ${f}`);
  ids.add(def.id);
}
const lines = [
  '// SPDX-License-Identifier: AGPL-3.0-or-later',
  '// Generated by scripts/gen-symbol-index.mjs. Do not edit.',
  "import type { SymbolDef } from '../model/types.ts';",
  ...list.map((f, i) => `import s${i} from './${relative(DIR, f).replace(/\\/g, '/')}' with { type: 'json' };`),
  '',
  `export const SYMBOL_DEFS = [${list.map((_, i) => `s${i}`).join(', ')}] as unknown as SymbolDef[];`,
  '',
];
const text = lines.join('\n');
if (process.argv.includes('--check')) {
  const cur = await readFile(OUT, 'utf8').catch(() => '');
  if (cur !== text) {
    console.error('src/symbols/index.generated.ts is out of date: run npm run symbols');
    process.exit(1);
  }
} else {
  await writeFile(OUT, text);
  console.log(`${list.length} symbols → ${relative(process.cwd(), OUT)}`);
}
