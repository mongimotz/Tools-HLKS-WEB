// Site-wide colour palette switch (owner only, not a user setting).
//   node scripts/palette.mjs            prints the active palette and the available ones
//   node scripts/palette.mjs wave       writes docs/palettes/wave.json into tokens.css and the favicon
// Palettes live in docs/palettes/<id>.json (light + dark column, the same token names).
// tokens.css keeps everything between the palette markers generated; edit the JSON, then run this script.

import { readFile, writeFile, readdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
const TOKENS = new URL('assets/css/tokens.css', root);
const FAVICON = new URL('assets/favicon.svg', root);
const BEGIN = '/* palette:begin';
const END = '/* palette:end */';

export async function listPalettes() {
  const files = await readdir(new URL('docs/palettes/', root));
  return files.filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
}

export async function readPalette(id) {
  return JSON.parse(await readFile(new URL(`docs/palettes/${id}.json`, root), 'utf8'));
}

const decls = (col, indent) => Object.entries(col).map(([k, v]) => `${indent}--${k}: ${v};`).join('\n');

/** The generated tail of tokens.css: light :root, dark via the OS setting, dark via the theme button. */
export function paletteBlock(id, p) {
  return `${BEGIN} ${id} | ${p.name} (${p.base}): generated by scripts/palette.mjs from docs/palettes/${id}.json, do not edit by hand */
:root {
${decls(p.light, '  ')}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
    color-scheme: dark;
${decls(p.dark, '    ')}
  }
}

:root[data-theme='dark'] {
  color-scheme: dark;
${decls(p.dark, '  ')}
}
${END}
`;
}

/** Id of the palette tokens.css currently holds. */
export function activePalette(css) {
  return css.match(/\/\* palette:begin (\S+)/)?.[1] ?? null;
}

export function applyToTokens(css, id, p) {
  const a = css.indexOf(BEGIN);
  const b = css.indexOf(END);
  if (a < 0 || b < 0) throw new Error('tokens.css: palette markers missing');
  return css.slice(0, a) + paletteBlock(id, p) + css.slice(b + END.length + 1);
}

export function applyToFavicon(svg, p) {
  return svg
    .replace(/(<style>\.bg\{fill:)#[0-9a-f]{6}(\}\.fg\{stroke:)#[0-9a-f]{6}/i, `$1${p.light.primary}$2${p.light['on-primary']}`)
    .replace(/(@media \(prefers-color-scheme:dark\)\{\.bg\{fill:)#[0-9a-f]{6}(\}\.fg\{stroke:)#[0-9a-f]{6}/i, `$1${p.dark.primary}$2${p.dark['on-primary']}`);
}

async function main(id) {
  const css = await readFile(TOKENS, 'utf8');
  const ids = await listPalettes();
  if (!id) {
    console.log(`active: ${activePalette(css)}\navailable: ${ids.join(', ')}`);
    return;
  }
  if (!ids.includes(id)) throw new Error(`unknown palette "${id}" (available: ${ids.join(', ')})`);
  const p = await readPalette(id);
  await writeFile(TOKENS, applyToTokens(css, id, p));
  await writeFile(FAVICON, applyToFavicon(await readFile(FAVICON, 'utf8'), p));
  console.log(`palette: ${id} (${p.name}) written to tokens.css and favicon.svg`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv[2]).catch((e) => {
    console.error(e.message);
    process.exit(1);
  });
}
